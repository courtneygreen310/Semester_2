#import libraries
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
import matplotlib.pyplot as plt
import time

#load dataset
fashion_mnist = keras.datasets.fashion_mnist

(x_train, y_train), (x_test, y_test) = fashion_mnist.load_data()

x_train = x_train / 255.0
x_test = x_test / 255.0

x_train = x_train.reshape(-1, 28, 28, 1)
x_test = x_test.reshape(-1, 28, 28, 1)

#create CNN model
def create_model():
    model = keras.Sequential([
        layers.Conv2D(32, (3,3), activation='relu', input_shape=(28,28,1)),
        layers.MaxPooling2D((2,2)),

        layers.Conv2D(64, (3,3), activation='relu'),
        layers.MaxPooling2D((2,2)),

        layers.Flatten(),
        layers.Dense(128, activation='relu'),
        layers.Dense(10, activation='softmax')
    ])

    model.compile(
        optimizer='adam',
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    return model

#single machine training
model = create_model()

start = time.time()

history_single = model.fit(
    x_train,
    y_train,
    epochs=10,
    validation_data=(x_test, y_test)
)

end = time.time()

single_time = end - start

print("Single machine training time:", single_time)

#distributed tensorflow

strategy = tf.distribute.MirroredStrategy()

with strategy.scope():
    distributed_model = create_model()

start = time.time()

history_distributed = distributed_model.fit(
    x_train,
    y_train,
    epochs=10,
    validation_data=(x_test, y_test)
)

end = time.time()

distributed_time = end - start

print("Distributed training time:", distributed_time)


#plot accuracy vs epochs

plt.plot(history_single.history['accuracy'], label='Single Machine')

plt.plot(history_distributed.history['accuracy'],
         label='Distributed')

plt.xlabel("Epochs")
plt.ylabel("Accuracy")
plt.title("Accuracy vs Epochs")

plt.legend()
plt.show()

