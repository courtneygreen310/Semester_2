#import libraries
import pandas as pd
import nltk
from nltk.sentiment.vader import SentimentIntensityAnalyzer
from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize
from nltk.stem import WordNetLemmatizer

#load nltk corpus
nltk.download('all')

df = pd.read_csv('/content/DisneylandReviews.csv', encoding='latin1')
print(df.head())

df.columns

#preprocessing function
def preprocess_text(text):
    tokens = word_tokenize(text.lower())
    filtered_tokens = [token for token in tokens if token not in stopwords.words('english')]

    lemmatizer = WordNetLemmatizer()
    lemmatized_tokens = [lemmatizer.lemmatize(token) for token in filtered_tokens]

    processed_text = ' '.join(lemmatized_tokens)
    return processed_text


df['Review_Text'] = df['Review_Text'].apply(preprocess_text)
print(df.head)

from nltk.sentiment.vader import SentimentIntensityAnalyzer

analyzer = SentimentIntensityAnalyzer()

def get_sentiment(text):
    scores = analyzer.polarity_scores(text)

    if scores['compound'] >= 0.05:
        return 1
    elif scores['compound'] <= -0.05:
        return -1
    else:
        return 0

def rating_to_sentiment(rating):
    if rating >= 4:
        return 1
    elif rating <= 2:
        return -1
    else:
        return 0

df['true_sentiment'] = df['Rating'].apply(rating_to_sentiment)

from sklearn.metrics import confusion_matrix, classification_report

print(confusion_matrix(df['true_sentiment'], df['sentiment']))
print(classification_report(df['true_sentiment'], df['sentiment']))