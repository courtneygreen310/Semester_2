import nltk
from nltk.tokenize import word_tokenize
from nltk import pos_tag
nltk.download('punkt_tab')
nltk.download('averaged_perceptron_tagger_eng')

text = "Dear all of you beautiful souls. A man who loves you does not: 1. Humiliate you on social media 2. Beat you 3. Cheat on you 4. Call you out of your name/put you down to lower your self esteem due to his own insecurities. 5. Hide his phone, passwords, where abouts, etc."
words = word_tokenize(text)

pos_tags = pos_tag(words)

for w in words:
  print(w)

print("Original Text:")
print(text)

print("\nPoS Tagging Result:")
for word, pos_tag in pos_tags:
    print(f"{word}: {pos_tag}")

import re
from nltk.tokenize import word_tokenize
from nltk import pos_tag

text = "Dear all of you beautiful souls. A man who loves you does not: 1. Humiliate you on social media 2. Beat you 3. Cheat on you 4. Call you out of your name/put you down to lower your self esteem due to his own insecurities. 5. Hide his phone, passwords, where abouts, etc."

#Text normalisation
lower_text = text.lower()
no_number_text = re.sub(r'\d+', '', lower_text)

#text tokenizer
words = word_tokenize(no_number_text)

#parts of speech tagging
pos_tags = pos_tag(words)

print(words)
print(pos_tags)