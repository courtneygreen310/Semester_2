#text tokenization with no libraries
sentence = "Streetwear and crop tops take World Cup fashion to new heights"
print(sentence.split())

paragraph = "And this year's campaigns from the two main kit-makers - Adidas and Nike - mark a notable departure from previous competitions, featuring more streetwear-inspired collections than traditional matching football shorts, socks and boots."
print(paragraph.split())

from nltk.tokenize import WhitespaceTokenizer
tokenizer = WhitespaceTokenizer()

clean_tokens = tokenizer.tokenize(paragraph)
print(clean_tokens)

#text tokenization with nltk
import nltk
nltk.download('punkt_tab')
from nltk.tokenize import word_tokenize
print(word_tokenize(paragraph))

#tokenization using spacy
import spacy

nlp = spacy.blank("en")

text = "And this year's campaigns from the two main kit-makers - Adidas and Nike - mark a notable departure from previous competitions, featuring more streetwear-inspired collections than traditional matching football shorts, socks and boots."

doc = nlp(text)

tokens = [token.text for token in doc]

print(tokens)

#stop words
from nltk.corpus import stopwords
nltk.download('stopwords')
stop_words = set(stopwords.words('english'))

#removing stop words
for w in clean_tokens:
  if w not in stop_words:
    print(w)

#stemming
from nltk.stem import PorterStemmer

ps = PorterStemmer()

words = ['And', 'this', 'year', "'s", 'campaigns', 'from', 'the', 'two',
         'main', 'kit', '-', 'makers', '-', 'Adidas', 'and', 'Nike', '-',
         'mark', 'a', 'notable', 'departure', 'from', 'previous', 'competitions',
         ',', 'featuring', 'more', 'streetwear', '-', 'inspired', 'collections',
         'than', 'traditional', 'matching', 'football', 'shorts', ',', 'socks',
         'and', 'boots', '.']

stemmed_words = [ps.stem(word) for word in words]

print(stemmed_words)