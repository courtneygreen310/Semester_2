#implement sequential merge sort
def merge(left, right):
    result = []
    i = j = 0

    while i < len(left) and j < len(right):
        if left[i] <= right[j]:
            result.append(left[i])
            i += 1
        else:
            result.append(right[j])
            j += 1

    result.extend(left[i:])
    result.extend(right[j:])
    return result


def merge_sort(arr):
    if len(arr) <= 1:
        return arr

    mid = len(arr) // 2
    left = merge_sort(arr[:mid])
    right = merge_sort(arr[mid:])
    return merge(left, right)

#implement parallel merge sort
def parallel_merge_sort(arr):
    if len(arr) <= 5000:  # cutoff to avoid overhead
        return merge_sort(arr)

    mid = len(arr) // 2
    left = arr[:mid]
    right = arr[mid:]

    with Pool(processes=2) as pool:
        left_sorted, right_sorted = pool.map(merge_sort, [left, right])

    return merge(left_sorted, right_sorted)

#implement sequential quick sort
def quick_sort(arr):
    if len(arr) <= 1:
        return arr

    pivot = arr[len(arr) // 2]
    left = [x for x in arr if x < pivot]
    middle = [x for x in arr if x == pivot]
    right = [x for x in arr if x > pivot]

    return quick_sort(left) + middle + quick_sort(right)

#implement parallel quick sort
def parallel_quick_sort(arr):
    if len(arr) <= 5000:
        return quick_sort(arr)

    pivot = arr[len(arr) // 2]
    left = [x for x in arr if x < pivot]
    middle = [x for x in arr if x == pivot]
    right = [x for x in arr if x > pivot]

    with Pool(processes=2) as pool:
        left_sorted, right_sorted = pool.map(quick_sort, [left, right])

    return left_sorted + middle + right_sorted

#time function
def time_function(func, data):
    start = time.time()
    result = func(data)
    end = time.time()
    return end - start, result

#speedup calculation
def calculate_speedup(seq_time, par_time, label):
    speedup = seq_time / par_time if par_time > 0 else 0
    efficiency = (speedup / cpu_count()) * 100

    print(f"\n--- {label} ---")
    print(f"Sequential time: {seq_time:.4f}s")
    print(f"Parallel time:   {par_time:.4f}s")
    print(f"Speedup:         {speedup:.2f}x")
    print(f"Efficiency:      {efficiency:.1f}%")

