"""Text preprocessing"""

import re
import nltk
from nltk.corpus import stopwords

nltk.download('stopwords')

stop_words = set(stopwords.words('english'))

def clean_resume(text):
    text = re.sub(r'http\S+', '', text)
    text = re.sub(r'[^a-zA-Z ]', '', text)
    text = text.lower()

    words = text.split()
    words = [word for word in words if word not in stop_words]

    return " ".join(words)

df["Cleaned_Resume"] = df["Resume"].apply(clean_resume)

"""Testing"""

job_description = """
Looking for a Data Analyst, that has skills in Python, SQL, can draw insights from data and present them using data visualisation, using Power BI tools
"""

from sklearn.feature_extraction.text import TfidfVectorizer

vectorizer = TfidfVectorizer()

tfidf_matrix = vectorizer.fit_transform(
    df["Cleaned_Resume"].tolist() + [job_description]
)

from sklearn.metrics.pairwise import cosine_similarity

similarity_scores = cosine_similarity(
    tfidf_matrix[-1],
    tfidf_matrix[:-1]
)

df["Similarity_Score"] = similarity_scores.flatten()

top_candidates = df.sort_values(
    by="Similarity_Score",
    ascending=False
)

