#import libraries
import pandas as pd

#import dataset
df = pd.read_csv('Activity.csv')
df.head()

df.info()

df['UserID'].nunique()

df["Date"] = pd.to_datetime(df["Date"])

#missing values count
df.isna().sum()

#check for dublicates
df.duplicated().sum()

df.describe()

#new columns
df["Total_Active_Minutes"] = (
    df["Very_Active_Minutes"] +
    df["Fairly_Active_Minutes"] +
    df["Lightly_Active_Minutes"])

df["Activity_Ratio"] = df["Total_Active_Minutes"] / (
    df["Total_Active_Minutes"] + df["Sedentary_Minutes"]
)

df[df['Total_Active_Minutes'] == 0]['UserID'].nunique()

df["Total_Active_Minutes"].describe()

df.groupby("UserID")["Steps"].mean().head(10)

df.groupby('UserID')['Total_Active_Minutes'].sum()

import matplotlib.pyplot as plt

user_activity = df.groupby('UserID')['Total_Active_Minutes'].sum()

plt.figure(figsize=(10,5))
user_activity.plot(kind='bar')

plt.title('Total Fairly Active Minutes per User')
plt.xlabel('UserID')
plt.ylabel('Total Fairly Active Minutes')

plt.show()

df.groupby('UserID')['Total_Active_Minutes'].mean()

import matplotlib.pyplot as plt

avg_activity = df.groupby('UserID')['Total_Active_Minutes'].mean()

plt.figure(figsize=(12,6))
avg_activity.plot(kind='bar')

plt.title('Average Active Minutes per User')
plt.xlabel('UserID')
plt.ylabel('Average Active Minutes')

plt.xticks(rotation=90)
plt.tight_layout()
plt.show()

