#PCFG text generation
from nltk import PCFG
from nltk.parse.generate import generate

grammar = PCFG.fromstring("""
S -> NP VP [1.0]

NP -> Name [0.6] | N [0.4]

VP -> V NP [0.7] | V [0.3]

Det -> 'the' [1.0]

N -> 'chocolate' [0.5] | 'cars' [0.5]

V -> 'likes' [0.6] | 'ate' [0.4]

Name -> 'Michael' [1.0]
""")

print(grammar.start())
print(grammar.productions())

for sentence in generate(grammar, n=5, depth=5):
    print(' '.join(sentence))

